#!/usr/bin/env python3
"""
export_rdf — emit the graph as Turtle, with families as super-properties.

Read-only, like kg_query: seed.json is opened and never written. The output goes
to stdout unless --out names a file.

The shape is the two-tier pattern the precedents table takes from W3C
(FAMILY_DEFINITIONS v0.7.1, line 125): verbatim relations are leaf properties,
families are super-properties, and nothing is renamed. What this exporter
deliberately does NOT emit is documented in the header it writes into every
file it produces.
"""
from __future__ import annotations

import argparse
import datetime
import os
import re
import sys
from urllib.parse import quote

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from kg_query import (  # noqa: E402
    Graph, active_declarations, effective_relation, load_json,
    DEFAULT_SEED, DEFAULT_DECLARATIONS,
)

# Provisional. The repository has a DOI (10.5281/zenodo.21631523) and a site
# (symbolicworld.observer) but has never minted a term namespace; picking one is
# a decision for a human, so this is marked provisional wherever it appears.
BASE = "https://symbolicworld.observer/jungkg/ns/"
PREFIXES = [
    ("rdf", "http://www.w3.org/1999/02/22-rdf-syntax-ns#"),
    ("rdfs", "http://www.w3.org/2000/01/rdf-schema#"),
    ("owl", "http://www.w3.org/2002/07/owl#"),
    ("jkg", BASE),
    ("jkgf", BASE + "family/"),
    ("jkgp", BASE + "relation/"),
    ("jkgn", BASE + "node/"),
]

SAFE_LOCAL = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_-]*\Z")


def term(prefix, base, local):
    """A prefixed name where the local part is safe for one, else a full IRI."""
    if SAFE_LOCAL.fullmatch(local):
        return f"{prefix}:{local}"
    # a full IRI may not contain spaces or the characters < > " { } | \ ^ `;
    # percent-encode the local part (a verbatim relation string can carry any of them)
    return f"<{base}{quote(local, safe='-_.~!$&*+,;=:@/')}>"


def literal(text):
    escaped = (text.replace("\\", "\\\\").replace('"', '\\"')
               .replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t"))
    return f'"{escaped}"'


def header(graph, declarations, split_strings, unresolved_declarations):
    today = datetime.date.today().isoformat()
    lines = [
        "# JungKG — relation vocabulary and edges, Turtle.",
        f"# Generated by tools/query/export_rdf.py on {today} from",
        f"# {os.path.basename(graph.path)} sha256:{graph.digest[:12]} "
        f"({len(graph.nodes)} nodes, {len(graph.edges)} edges) and",
        f"# {os.path.basename(declarations['_path'])}, transcribed from "
        f"FAMILY_DEFINITIONS "
        f"{declarations.get('transcribed_from', {}).get('document_version', '?')}.",
        "#",
        "# THE NAMESPACE IS PROVISIONAL. This repository has never minted one; the",
        f"# base IRI {BASE} is a placeholder chosen by",
        "# the exporter so the file parses, and it should be settled by a human",
        "# before anything is published against it.",
        "#",
        "# Shape: verbatim relations are leaf properties, families are",
        "# super-properties (FAMILY_DEFINITIONS line 125, the W3C two-tier",
        "# pattern). Nothing is renamed; the frozen relation layer stays frozen.",
        "#",
        "# NO TRANSITIVITY AXIOM APPEARS IN THIS FILE, on any property or family.",
        "# FAMILY_DEFINITIONS rejects transitivity outright (line 131): the",
        "# alchemical sequences this graph records are cyclical — the uroboros and",
        "# the Rex cycle — so a transitive `precedes` derives A precedes A. A",
        "# reasoner reading this file will not manufacture chains, because the file",
        "# licenses none.",
        "#",
        "# rdfs:subPropertyOf is asserted ONLY for relation strings that sit in",
        "# exactly one family across the whole graph. Family assignment is per EDGE",
        "# and never per string (FAMILY_DEFINITIONS, rule 1), so a string used in",
        "# two families has no true string-level super-property and gets none here.",
        f"# {len(split_strings)} of the graph's assigned strings split that way; they are",
        "# listed below the family block, with the families they span, and they",
        "# still appear as leaf properties on their edges.",
        "#",
        "# A plain triple carries no family, so the per-edge assignment does not",
        "# survive into the edge block. Read the family of an individual edge from",
        "# seed.json or `kg_query.py --family`, not from this file.",
        "#",
        "# Leaf properties are emitted for the verbatim relation strings AND the",
        "# normalized ones, because both layers are part of the vocabulary and the",
        "# frozen layer stays frozen. Edge triples use the effective relation only,",
        "# so a verbatim string that was normalized away carries no triple here.",
        "#",
        "# owl:inverseOf and owl:SymmetricProperty come only from the ACTIVE",
        "# declarations, one axiom per declaration.",
    ]
    if unresolved_declarations:
        lines += [
            "# Declarations restricted to one family are NOT emitted as axioms:",
            "# OWL has no way to scope an inverse to a subset of a property's uses,",
            "# and an unscoped axiom would say more than the document declared.",
        ]
        for decl in unresolved_declarations:
            lines.append(f"#   withheld: {decl['id']} "
                         f"(declared for family {decl['applies_to_family']} only)")
    lines += [
        "#",
        "# References, quotes, provenance and family state are NOT exported. This",
        "# file is the vocabulary and the edges; the evidence stays in seed.json.",
        "",
    ]
    return lines


def build(graph, declarations):
    families = graph.family_of_string()
    string_families = {}
    for family, strings in families.items():
        for string in strings:
            string_families.setdefault(string, set()).add(family)
    split = sorted(s for s, f in string_families.items() if len(f) > 1)
    single = {s: next(iter(f)) for s, f in string_families.items() if len(f) == 1}

    restricted = [d for d in active_declarations(declarations)
                  if d.get("applies_to_family")]

    out = header(graph, declarations, split, restricted)
    for prefix, iri in PREFIXES:
        out.append(f"@prefix {prefix}: <{iri}> .")
    out.append("")

    out.append("# ---- families as super-properties " + "-" * 41)
    out.append("")
    for family in sorted(families):
        out.append(f"{term('jkgf', PREFIXES[4][1], family)} a rdf:Property ;")
        out.append(f"    rdfs:label {literal(family)} ;")
        out.append(f"    rdfs:comment {literal(f'Relation family {family}, as defined in docs/FAMILY_DEFINITIONS.md. An assignment on record, not a verified fact.')} .")
        out.append("")

    out.append("# ---- leaf properties " + "-" * 54)
    out.append("")
    all_strings = sorted({effective_relation(e) for e in graph.edges}
                         | {e["relation"] for e in graph.edges})
    for string in all_strings:
        subject = term("jkgp", PREFIXES[5][1], string)
        out.append(f"{subject} a rdf:Property ;")
        if string in single:
            out.append(f"    rdfs:label {literal(string)} ;")
            out.append(f"    rdfs:subPropertyOf "
                       f"{term('jkgf', PREFIXES[4][1], single[string])} .")
        else:
            out.append(f"    rdfs:label {literal(string)} .")
        out.append("")

    out.append("# ---- strings this graph uses in more than one family " + "-" * 22)
    out.append("# No super-property is asserted for these; the family lives on the edge.")
    for string in split:
        out.append(f"#   {string}: " + ", ".join(sorted(string_families[string])))
    out.append("")

    out.append("# ---- declared inverses and symmetry " + "-" * 39)
    out.append("")
    for decl in active_declarations(declarations):
        if decl.get("applies_to_family"):
            continue
        if decl["kind"] == "inverse":
            out.append(f"{term('jkgp', PREFIXES[5][1], decl['forward'])} owl:inverseOf "
                       f"{term('jkgp', PREFIXES[5][1], decl['inverse'])} .")
        else:
            out.append(f"{term('jkgp', PREFIXES[5][1], decl['relation'])} a "
                       f"owl:SymmetricProperty .")
    out.append("")

    out.append("# ---- nodes " + "-" * 64)
    out.append("")
    for node in graph.nodes:
        out.append(f"{term('jkgn', PREFIXES[6][1], node['id'])} a jkg:Node ;")
        out.append(f"    rdfs:label {literal(node.get('label', node['id']))} ;")
        out.append(f"    jkg:nodeType {literal(node.get('type', 'unknown'))} .")
        out.append("")

    out.append("# ---- edges " + "-" * 64)
    out.append("# One triple per stored edge, on the EFFECTIVE relation. No derived,")
    out.append("# inferred or closure row appears here.")
    out.append("")
    for edge in graph.edges:
        out.append(
            f"{term('jkgn', PREFIXES[6][1], edge['subject'])} "
            f"{term('jkgp', PREFIXES[5][1], effective_relation(edge))} "
            f"{term('jkgn', PREFIXES[6][1], edge['object'])} ."
        )
    out.append("")
    return "\n".join(out)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="export_rdf",
        description="Emit seed.json as Turtle. Read-only; the graph is never written.")
    parser.add_argument("--seed", default=DEFAULT_SEED)
    parser.add_argument("--declarations", default=DEFAULT_DECLARATIONS)
    parser.add_argument("--out", help="write here instead of stdout")
    args = parser.parse_args(argv)

    graph = Graph(args.seed)
    declarations = load_json(args.declarations)
    declarations["_path"] = args.declarations
    turtle = build(graph, declarations)

    if args.out:
        with open(args.out, "w", encoding="utf-8") as fh:
            fh.write(turtle)
        print(f"wrote {args.out}: {len(turtle.splitlines())} lines, "
              f"{len(graph.edges)} edge triples", file=sys.stderr)
    else:
        sys.stdout.write(turtle)
    return 0


if __name__ == "__main__":
    sys.exit(main())
