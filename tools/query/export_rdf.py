"""
export_rdf — emit the graph as Turtle, with families as super-properties.

Read-only, like kg_query: seed.json is opened and never written. With --out-dir
it writes the four files of the publishable export; otherwise it prints the
structure and provenance file to stdout, or to --out.

The shape is the two-tier pattern the precedents table takes from W3C
(FAMILY_DEFINITIONS v0.7.1, line 125): verbatim relations are leaf properties,
families are super-properties, and nothing is renamed. What this exporter
deliberately does NOT emit is documented in the header it writes into every
file it produces.
"""
